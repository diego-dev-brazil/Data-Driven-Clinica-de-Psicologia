CREATE MATERIALIZED VIEW MV_FINANCEIRO AS
WITH REGISTROS_MENSAIS AS (
    SELECT
        MEN_ID AS ID_REGISTRO,
        MEN_ACO_ID AS ID_ACOMPANHAMENTO,
        MEN_PERIODO AS PERIODO,
        MEN_VEZES_MES AS QTD_CONSULTAS,
        NVL(MEN_VEZES_FALTA, 0) AS QTD_FALTAS,
        MEN_VALOR_MENSAL AS VALOR_MENSAL,
        CAST(NULL AS DATE) AS DATA_REFERENCIA,
        'ATUAL' AS TIPO
    FROM APP.ACOMPANHAMENTOS_MENSAIS

    UNION ALL

    SELECT
        HMEN_ID,
        HMEN_ACO_ID,
        HMEN_PERIODO,
        HMEN_VEZES_MES,
        NVL(HMEN_VEZES_FALTA, 0),
        HMEN_VALOR_MENSAL,
        HMEN_DT_ENTRADA,
        'HISTORICO'
    FROM APP.HACOMPANHAMENTOS_MENSAIS
),

ACOMPANHAMENTOS_BASE AS (
    SELECT
        ACO_ID AS ID_ACOMPANHAMENTO,
        ACO_NOME_PACIENTE AS PACIENTE,
        ACO_MOD_ID AS ID_MODALIDADE,
        CAST(NULL AS DATE) AS DATA_VERSAO,
        'ATUAL' AS TIPO
    FROM APP.ACOMPANHAMENTOS

    UNION ALL

    SELECT
        HACO_ID,
        HACO_NOME_PACIENTE,
        HACO_MOD_ID,
        HACO_DT_ENTRADA,
        'HISTORICO'
    FROM APP.HACOMPANHAMENTOS
),

ACOMPANHAMENTOS_CANDIDATOS AS (
    SELECT
        M.ID_REGISTRO,
        M.DATA_REFERENCIA,
        M.PERIODO,
        M.QTD_CONSULTAS,
        M.QTD_FALTAS,
        M.VALOR_MENSAL,
        A.PACIENTE,
        A.ID_MODALIDADE,
        A.DATA_VERSAO AS DATA_VERSAO_ACOMPANHAMENTO,
        ROW_NUMBER() OVER (
            PARTITION BY M.ID_REGISTRO, M.DATA_REFERENCIA
            ORDER BY
                CASE
                    WHEN A.DATA_VERSAO IS NULL THEN 1
                    ELSE 0
                END,
                A.DATA_VERSAO ASC
        ) AS RN_ACOMPANHAMENTO
    FROM REGISTROS_MENSAIS M
    LEFT JOIN ACOMPANHAMENTOS_BASE A
        ON A.ID_ACOMPANHAMENTO = M.ID_ACOMPANHAMENTO
       AND (
            (M.DATA_REFERENCIA IS NULL AND A.TIPO = 'ATUAL')
            OR (
                M.DATA_REFERENCIA IS NOT NULL
                AND (
                    A.DATA_VERSAO >= M.DATA_REFERENCIA
                    OR A.TIPO = 'ATUAL'
                )
            )
       )
),

ACOMPANHAMENTOS_ESCOLHIDOS AS (
    SELECT *
    FROM ACOMPANHAMENTOS_CANDIDATOS
    WHERE RN_ACOMPANHAMENTO = 1
),

MODALIDADES_BASE AS (
    SELECT
        MOD_ID AS ID_MODALIDADE,
        MOD_NOME AS MODALIDADE,
        CAST(NULL AS DATE) AS DATA_VERSAO,
        'ATUAL' AS TIPO
    FROM APP.MODALIDADES

    UNION ALL

    SELECT
        HMOD_ID,
        HMOD_NOME,
        HMOD_DT_ENTRADA,
        'HISTORICO'
    FROM APP.HMODALIDADES
),

MODALIDADES_CANDIDATAS AS (
    SELECT
        A.*,
        M.MODALIDADE,
        ROW_NUMBER() OVER (
            PARTITION BY A.ID_REGISTRO, A.DATA_REFERENCIA
            ORDER BY
                CASE
                    WHEN M.DATA_VERSAO IS NULL THEN 1
                    ELSE 0
                END,
                M.DATA_VERSAO ASC
        ) AS RN_MODALIDADE
    FROM ACOMPANHAMENTOS_ESCOLHIDOS A
    LEFT JOIN MODALIDADES_BASE M
        ON M.ID_MODALIDADE = A.ID_MODALIDADE
       AND (
            (A.DATA_VERSAO_ACOMPANHAMENTO IS NULL AND M.TIPO = 'ATUAL')
            OR (
                A.DATA_VERSAO_ACOMPANHAMENTO IS NOT NULL
                AND (
                    M.DATA_VERSAO >= A.DATA_VERSAO_ACOMPANHAMENTO
                    OR M.TIPO = 'ATUAL'
                )
            )
       )
),

MODALIDADES_ESCOLHIDAS AS (
    SELECT *
    FROM MODALIDADES_CANDIDATAS
    WHERE RN_MODALIDADE = 1
),

ASSOCIACOES_BASE AS (
    SELECT
        ACOD_ACO_ID AS ID_ACOMPANHAMENTO,
        ACOD_DIAG_ID AS ID_DIAGNOSTICO,
        CAST(NULL AS DATE) AS DATA_VERSAO,
        'ATUAL' AS TIPO
    FROM APP.ACOMPANHAMENTOS_DIAGNOSTICOS

    UNION ALL

    SELECT
        HACOD_ACO_ID,
        HACOD_DIAG_ID,
        HACOD_DT_ENTRADA,
        'HISTORICO'
    FROM APP.HACOMPANHAMENTOS_DIAGNOSTICOS
),

ASSOCIACOES_CANDIDATAS AS (
    SELECT
        M.ID_REGISTRO,
        M.DATA_REFERENCIA,
        A.ID_DIAGNOSTICO,
        A.DATA_VERSAO AS DATA_VERSAO_ASSOCIACAO,
        ROW_NUMBER() OVER (
            PARTITION BY
                M.ID_REGISTRO,
                M.DATA_REFERENCIA,
                A.ID_DIAGNOSTICO
            ORDER BY
                CASE
                    WHEN A.DATA_VERSAO IS NULL THEN 1
                    ELSE 0
                END,
                A.DATA_VERSAO ASC
        ) AS RN_ASSOCIACAO
    FROM REGISTROS_MENSAIS M
    LEFT JOIN ASSOCIACOES_BASE A
        ON A.ID_ACOMPANHAMENTO = M.ID_ACOMPANHAMENTO
       AND (
            (M.DATA_REFERENCIA IS NULL AND A.TIPO = 'ATUAL')
            OR (
                M.DATA_REFERENCIA IS NOT NULL
                AND (
                    A.DATA_VERSAO >= M.DATA_REFERENCIA
                    OR A.TIPO = 'ATUAL'
                )
            )
       )
),

ASSOCIACOES_ESCOLHIDAS AS (
    SELECT *
    FROM ASSOCIACOES_CANDIDATAS
    WHERE RN_ASSOCIACAO = 1
),

DIAGNOSTICOS_BASE AS (
    SELECT
        DIAG_ID AS ID_DIAGNOSTICO,
        DIAG_NOME AS DIAGNOSTICO,
        CAST(NULL AS DATE) AS DATA_VERSAO
    FROM APP.DIAGNOSTICOS

    UNION ALL

    SELECT
        HDIAG_ID,
        HDIAG_NOME,
        HDIAG_DT_ENTRADA
    FROM APP.HDIAGNOSTICOS
),

DIAGNOSTICOS_CANDIDATOS AS (
    SELECT
        A.ID_REGISTRO,
        A.DATA_REFERENCIA,
        D.DIAGNOSTICO,
        ROW_NUMBER() OVER (
            PARTITION BY
                A.ID_REGISTRO,
                A.DATA_REFERENCIA,
                A.ID_DIAGNOSTICO
            ORDER BY
                CASE
                    WHEN D.DATA_VERSAO IS NULL THEN 1
                    ELSE 0
                END,
                D.DATA_VERSAO ASC
        ) AS RN_DIAGNOSTICO
    FROM ASSOCIACOES_ESCOLHIDAS A
    LEFT JOIN DIAGNOSTICOS_BASE D
        ON D.ID_DIAGNOSTICO = A.ID_DIAGNOSTICO
       AND (
            (A.DATA_VERSAO_ASSOCIACAO IS NULL AND D.DATA_VERSAO IS NULL)
            OR (
                A.DATA_VERSAO_ASSOCIACAO IS NOT NULL
                AND (
                    D.DATA_VERSAO >= A.DATA_VERSAO_ASSOCIACAO
                    OR D.DATA_VERSAO IS NULL
                )
            )
       )
),

DIAGNOSTICOS_AGREGADOS AS (
    SELECT
        ID_REGISTRO,
        DATA_REFERENCIA,
        LISTAGG(DIAGNOSTICO, ', ') WITHIN GROUP (ORDER BY DIAGNOSTICO) AS DIAGNOSTICO
    FROM DIAGNOSTICOS_CANDIDATOS
    WHERE RN_DIAGNOSTICO = 1
    GROUP BY ID_REGISTRO, DATA_REFERENCIA
)

SELECT
    NVL(A.PACIENTE, 'Não informado') AS PACIENTE,
    NVL(D.DIAGNOSTICO, 'Não informado') AS DIAGNOSTICO,
    NVL(A.MODALIDADE, 'Não informada') AS MODALIDADE,
    A.PERIODO,
    A.QTD_CONSULTAS,
    A.QTD_FALTAS,
    A.VALOR_MENSAL
FROM MODALIDADES_ESCOLHIDAS A
LEFT JOIN DIAGNOSTICOS_AGREGADOS D
    ON D.ID_REGISTRO = A.ID_REGISTRO
   AND (
        D.DATA_REFERENCIA = A.DATA_REFERENCIA
        OR (
            D.DATA_REFERENCIA IS NULL
            AND A.DATA_REFERENCIA IS NULL
        )
   );
