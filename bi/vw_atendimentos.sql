CREATE OR REPLACE VIEW VW_ATENDIMENTOS1 AS
WITH MENSAIS_BASE AS (
    SELECT
        MEN_ID AS ID_REGISTRO,
        MEN_ACO_ID AS ID_ACOMPANHAMENTO,
        MEN_PERIODO AS PERIODO,
        NVL(MEN_VEZES_MES, 0) AS QTD_CONSULTAS,
        NVL(MEN_VEZES_FALTA, 0) AS QTD_FALTAS,
        MEN_VALOR_MENSAL AS VALOR_MENSAL,
        CAST(NULL AS DATE) AS DATA_REFERENCIA,
        'ATUAL' AS TIPO
    FROM APP.ACOMPANHAMENTOS_MENSAIS

    UNION ALL

    SELECT
        HMEN_ID,
        HMEN_ACO_ID,
        HMEN_PERIODO,
        NVL(HMEN_VEZES_MES, 0),
        NVL(HMEN_VEZES_FALTA, 0),
        HMEN_VALOR_MENSAL,
        HMEN_DT_ENTRADA,
        'HISTORICO'
    FROM APP.HACOMPANHAMENTOS_MENSAIS
),

ACOMPANHAMENTOS_BASE AS (
    SELECT
        ACO_ID AS ID_ACOMPANHAMENTO,
        ACO_NOME_PACIENTE AS PACIENTE,
        ACO_STATUS AS STATUS,
        ACO_DATA_INICIO AS DATA_INICIO,
        ACO_DATA_FIM AS DATA_FIM,
        ACO_MOD_ID AS ID_MODALIDADE,
        ACO_MOT_ID AS ID_MOTIVO_SAIDA,
        CAST(NULL AS DATE) AS DATA_VERSAO,
        'ATUAL' AS TIPO
    FROM APP.ACOMPANHAMENTOS

    UNION ALL

    SELECT
        HACO_ID,
        HACO_NOME_PACIENTE,
        HACO_STATUS,
        HACO_DATA_INICIO,
        HACO_DATA_FIM,
        HACO_MOD_ID,
        HACO_MOT_ID,
        HACO_DT_ENTRADA,
        'HISTORICO'
    FROM APP.HACOMPANHAMENTOS
),

ACOMPANHAMENTOS_RELACIONADOS AS (
    SELECT
        M.*,
        A.PACIENTE,
        A.STATUS,
        A.DATA_INICIO,
        A.DATA_FIM,
        A.ID_MODALIDADE,
        A.ID_MOTIVO_SAIDA,
        ROW_NUMBER() OVER (
            PARTITION BY M.ID_REGISTRO, M.DATA_REFERENCIA
            ORDER BY
                CASE
                    WHEN A.DATA_VERSAO IS NULL THEN 1
                    ELSE 0
                END,
                A.DATA_VERSAO ASC
        ) AS RN
    FROM MENSAIS_BASE M
    LEFT JOIN ACOMPANHAMENTOS_BASE A
        ON A.ID_ACOMPANHAMENTO = M.ID_ACOMPANHAMENTO
       AND (
            (M.DATA_REFERENCIA IS NULL AND A.TIPO = 'ATUAL')
            OR (
                M.DATA_REFERENCIA IS NOT NULL
                AND (
                    A.DATA_VERSAO >= M.DATA_REFERENCIA
                    OR A.TIPO = 'ATUAL'
                )
            )
       )
),

MODALIDADES_BASE AS (
    SELECT
        MOD_ID AS ID_MODALIDADE,
        MOD_NOME AS MODALIDADE,
        CAST(NULL AS DATE) AS DATA_VERSAO,
        'ATUAL' AS TIPO
    FROM APP.MODALIDADES

    UNION ALL

    SELECT
        HMOD_ID,
        HMOD_NOME,
        HMOD_DT_ENTRADA,
        'HISTORICO'
    FROM APP.HMODALIDADES
),

MODALIDADES_RELACIONADAS AS (
    SELECT
        A.*,
        M.MODALIDADE,
        ROW_NUMBER() OVER (
            PARTITION BY A.ID_REGISTRO, A.DATA_REFERENCIA
            ORDER BY
                CASE
                    WHEN M.DATA_VERSAO IS NULL THEN 1
                    ELSE 0
                END,
                M.DATA_VERSAO ASC
        ) AS RN_MODALIDADE
    FROM ACOMPANHAMENTOS_RELACIONADOS A
    LEFT JOIN MODALIDADES_BASE M
        ON M.ID_MODALIDADE = A.ID_MODALIDADE
       AND (
            (A.DATA_REFERENCIA IS NULL AND M.TIPO = 'ATUAL')
            OR (
                A.DATA_REFERENCIA IS NOT NULL
                AND (
                    M.DATA_VERSAO >= A.DATA_REFERENCIA
                    OR M.TIPO = 'ATUAL'
                )
            )
       )
    WHERE A.RN = 1
),

MOTIVOS_BASE AS (
    SELECT
        MOT_ID AS ID_MOTIVO_SAIDA,
        MOT_NOME AS MOTIVO_SAIDA,
        CAST(NULL AS DATE) AS DATA_VERSAO,
        'ATUAL' AS TIPO
    FROM APP.MOTIVO_SAIDAS

    UNION ALL

    SELECT
        HMOT_ID,
        HMOT_NOME,
        HMOT_DT_ENTRADA,
        'HISTORICO'
    FROM APP.HMOTIVO_SAIDAS
),

MOTIVOS_RELACIONADOS AS (
    SELECT
        A.*,
        MS.MOTIVO_SAIDA,
        ROW_NUMBER() OVER (
            PARTITION BY A.ID_REGISTRO, A.DATA_REFERENCIA
            ORDER BY
                CASE
                    WHEN MS.DATA_VERSAO IS NULL THEN 1
                    ELSE 0
                END,
                MS.DATA_VERSAO ASC
        ) AS RN_MOTIVO
    FROM MODALIDADES_RELACIONADAS A
    LEFT JOIN MOTIVOS_BASE MS
        ON MS.ID_MOTIVO_SAIDA = A.ID_MOTIVO_SAIDA
       AND (
            (A.DATA_REFERENCIA IS NULL AND MS.TIPO = 'ATUAL')
            OR (
                A.DATA_REFERENCIA IS NOT NULL
                AND (
                    MS.DATA_VERSAO >= A.DATA_REFERENCIA
                    OR MS.TIPO = 'ATUAL'
                )
            )
       )
    WHERE A.RN_MODALIDADE = 1
)

SELECT
    PACIENTE,
    PERIODO,
    EXTRACT(YEAR FROM PERIODO) AS ANO,
    EXTRACT(MONTH FROM PERIODO) AS MES,
    QTD_CONSULTAS,
    QTD_FALTAS,
    QTD_CONSULTAS + QTD_FALTAS AS TOTAL_CONSULTAS_PREVISTAS,
    CASE
        WHEN QTD_CONSULTAS + QTD_FALTAS = 0 THEN 0
        ELSE ROUND(
            QTD_CONSULTAS /
            (QTD_CONSULTAS + QTD_FALTAS) * 100,
            2
        )
    END AS PERCENTUAL_COMPARECIMENTO,
    VALOR_MENSAL,
    DATA_INICIO,
    DATA_FIM,
    CASE
        WHEN STATUS = 1 THEN 'Ativo'
        WHEN STATUS = 0 THEN 'Encerrado'
        ELSE 'Indeterminado'
    END AS STATUS_ACOMPANHAMENTO,
    MODALIDADE,
    MOTIVO_SAIDA
FROM MOTIVOS_RELACIONADOS
WHERE RN_MOTIVO = 1;
