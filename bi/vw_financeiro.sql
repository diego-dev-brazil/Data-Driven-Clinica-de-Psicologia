CREATE OR REPLACE VIEW VW_FINANCEIRO AS
WITH REGISTROS_MENSAIS AS (
    SELECT
        MEN_ID AS ID_REGISTRO,
        MEN_ACO_ID AS ID_ACOMPANHAMENTO,
        MEN_PERIODO AS PERIODO,
        MEN_VEZES_MES AS QTD_CONSULTAS,
        NVL(MEN_VEZES_FALTA, 0) AS QTD_FALTAS,
        MEN_VALOR_MENSAL AS VALOR_MENSAL,
        'ATUAL' AS ORIGEM_REGISTRO,
        CAST(NULL AS DATE) AS DATA_REGISTRO_HISTORICO
    FROM APP.ACOMPANHAMENTOS_MENSAIS

    UNION ALL

    SELECT
        HMEN_ID,
        HMEN_ACO_ID,
        HMEN_PERIODO,
        HMEN_VEZES_MES,
        NVL(HMEN_VEZES_FALTA, 0),
        HMEN_VALOR_MENSAL,
        'HISTORICO',
        HMEN_DT_ENTRADA
    FROM APP.HACOMPANHAMENTOS_MENSAIS
)
SELECT
    ID_REGISTRO,
    ID_ACOMPANHAMENTO,
    PERIODO,
    EXTRACT(YEAR FROM PERIODO) AS ANO,
    EXTRACT(MONTH FROM PERIODO) AS MES,
    QTD_CONSULTAS,
    QTD_FALTAS,
    VALOR_MENSAL,
    ORIGEM_REGISTRO,
    DATA_REGISTRO_HISTORICO
FROM REGISTROS_MENSAIS;
