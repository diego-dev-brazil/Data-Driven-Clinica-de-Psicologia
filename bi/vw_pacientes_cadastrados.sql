CREATE OR REPLACE VIEW VW_PACIENTES_CADASTROS AS
WITH ACOMPANHAMENTOS_BASE AS (
    SELECT
        ACO_ID AS ID_ACOMPANHAMENTO,
        ACO_STATUS AS STATUS,
        ACO_DATA_INICIO AS DATA_INICIO,
        ACO_DATA_FIM AS DATA_ENCERRAMENTO,
        ACO_MOD_ID AS ID_MODALIDADE,
        ACO_MOT_ID AS ID_MOTIVO_SAIDA,
        CAST(NULL AS DATE) AS DATA_REFERENCIA,
        'ATUAL' AS TIPO
    FROM APP.ACOMPANHAMENTOS

    UNION ALL

    SELECT
        HACO_ID,
        HACO_STATUS,
        HACO_DATA_INICIO,
        HACO_DATA_FIM,
        HACO_MOD_ID,
        HACO_MOT_ID,
        HACO_DT_ENTRADA,
        'HISTORICO'
    FROM APP.HACOMPANHAMENTOS
),
MODALIDADES_BASE AS (
    SELECT
        MOD_ID AS ID_MODALIDADE,
        MOD_NOME AS MODALIDADE,
        CAST(NULL AS DATE) AS DATA_VERSAO,
        'ATUAL' AS TIPO
    FROM APP.MODALIDADES

    UNION ALL

    SELECT
        HMOD_ID,
        HMOD_NOME,
        HMOD_DT_ENTRADA,
        'HISTORICO'
    FROM APP.HMODALIDADES
),
MOTIVOS_BASE AS (
    SELECT
        MOT_ID AS ID_MOTIVO_SAIDA,
        MOT_NOME AS MOTIVO_SAIDA,
        CAST(NULL AS DATE) AS DATA_VERSAO,
        'ATUAL' AS TIPO
    FROM APP.MOTIVO_SAIDAS

    UNION ALL

    SELECT
        HMOT_ID,
        HMOT_NOME,
        HMOT_DT_ENTRADA,
        'HISTORICO'
    FROM APP.HMOTIVO_SAIDAS
),
CADASTROS_RELACIONADOS AS (
    SELECT
        A.*,
        M.MODALIDADE,
        MS.MOTIVO_SAIDA,
        ROW_NUMBER() OVER (
            PARTITION BY
                A.ID_ACOMPANHAMENTO,
                A.DATA_REFERENCIA
            ORDER BY
                CASE
                    WHEN M.DATA_VERSAO IS NULL THEN 1
                    ELSE 0
                END,
                M.DATA_VERSAO ASC
        ) AS RN_MODALIDADE
    FROM ACOMPANHAMENTOS_BASE A
    LEFT JOIN MODALIDADES_BASE M
        ON M.ID_MODALIDADE = A.ID_MODALIDADE
       AND (
            (A.DATA_REFERENCIA IS NULL AND M.TIPO = 'ATUAL')
            OR
            (
                A.DATA_REFERENCIA IS NOT NULL
                AND (
                    M.DATA_VERSAO >= A.DATA_REFERENCIA
                    OR M.TIPO = 'ATUAL'
                )
            )
       )
    LEFT JOIN MOTIVOS_BASE MS
        ON MS.ID_MOTIVO_SAIDA = A.ID_MOTIVO_SAIDA
       AND (
            (A.DATA_REFERENCIA IS NULL AND MS.TIPO = 'ATUAL')
            OR
            (
                A.DATA_REFERENCIA IS NOT NULL
                AND (
                    MS.DATA_VERSAO >= A.DATA_REFERENCIA
                    OR MS.TIPO = 'ATUAL'
                )
            )
       )
)
SELECT
    ID_ACOMPANHAMENTO,
    STATUS,
    DATA_INICIO,
    DATA_ENCERRAMENTO,
    ID_MODALIDADE,
    MODALIDADE,
    ID_MOTIVO_SAIDA,
    MOTIVO_SAIDA,
    CASE
        WHEN DATA_ENCERRAMENTO IS NULL
            THEN 'SEM DATA DE ENCERRAMENTO'
        ELSE 'COM DATA DE ENCERRAMENTO'
    END AS SITUACAO_ENCERRAMENTO
FROM CADASTROS_RELACIONADOS
WHERE RN_MODALIDADE = 1;
